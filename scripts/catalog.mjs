import fs from 'node:fs';
import path from 'node:path';
import { ids, asset, read, write, resolve, snapshot } from './lib.mjs';
export function buildCatalog() {
  const entries=[];
  for(const id of ids()) {
    const dir=asset(id), meta=read(path.join(dir,'meta.json'));
    if(meta.status!=='ready')continue;
    const review=read(path.join(dir,'review.json')), actual=snapshot(dir);
    for(const [file,hash] of Object.entries(actual))if(review.hashes[file]!==hash)throw Error(`${id}/${file}: review is stale`);
    const motion=read(path.join(dir,'motion.json'));
    entries.push({...meta, files:Object.fromEntries(Object.keys(actual).map(name=>[name,`assets/${id}/${name}`])),sha256:actual,preset:motion.preset,fps:motion.fps??24,duration:3,animationBytes:fs.statSync(path.join(dir,'animated.avif')).size});
  }
  const catalog={version:1,license:'MIT',count:entries.length,entries};
  write(resolve('catalog.json'),catalog);
  const browser=entries.map(e=>({id:e.id,name:e.name,vi:e.terms?.vi?.text??'',category:e.category,preset:e.preset,fps:e.fps,bytes:e.animationBytes,search:Object.values(e.terms??{}).flatMap(t=>[t.text,t.reading??'']).join(' ')}));
  fs.writeFileSync(resolve('showcase/catalog.js'),`// Generated by npm run catalog; no fetch is required for file:// previews.\nwindow.EMOJI_CATALOG=${JSON.stringify(browser)};\n`);
  console.log(`Catalog: ${entries.length} reviewed emoji; ${Math.round(fs.statSync(resolve('showcase/catalog.js')).size/1024)} KiB browser index.`);
  return catalog;
}
if(process.argv[1]&&import.meta.url===new URL(`file://${path.resolve(process.argv[1])}`).href)buildCatalog();
